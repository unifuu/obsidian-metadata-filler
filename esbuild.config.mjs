import { createRequire } from "module";
import process from "process";

const require = createRequire(import.meta.url);
const dependencyRoot = process.env.METADATA_FILLER_BUILD_DEPS;
const esbuild = require(
	dependencyRoot
		? `${dependencyRoot}/esbuild`
		: "esbuild"
);
const builtinsModule = require(
	dependencyRoot
		? `${dependencyRoot}/builtin-modules`
		: "builtin-modules"
);
const builtins = builtinsModule.default ?? builtinsModule;

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins,
	],
	format: "cjs",
	target: "es2020",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	...(dependencyRoot ? { nodePaths: [dependencyRoot] } : {}),
	outfile: "main.js",
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
